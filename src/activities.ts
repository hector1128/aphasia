export function filterActivities(
  query: string,
  choices = activities,
): ActivityChoice[] {
  const terms = query.toLowerCase().trim().split(/\s+/).filter(Boolean);
  return choices.filter((choice) =>
    terms.every((term) => choice.name.toLowerCase().includes(term)),
  );
}
